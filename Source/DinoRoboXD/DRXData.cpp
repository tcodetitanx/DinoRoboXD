bool BuildingRunsRecipe(EBuilding B, const FRecipe& R)
{
	if (R.At == B) return true;
	// upgrades run lower-tier recipes
	if (R.At == EBuilding::Kiln && B == EBuilding::Furnace) return true;
	if (R.At == EBuilding::Workbench && (B == EBuilding::Assembler || B == EBuilding::AdvAssembler)) return true;
	if (R.At == EBuilding::Assembler && B == EBuilding::AdvAssembler) return true;
	if (R.At == EBuilding::FirePit && B == EBuilding::Smokehouse) return true;
	return false;
}

